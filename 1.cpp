#include <iostream>
#include <string>
#include <stack>
using namespace std;

int main() {
    string s;
    getline(cin, s);  // читаем всю строку целиком, включая пробелы

    stack<char> st;   // стек для хранения открывающих скобок
    bool ok = true;   // флаг: последовательность пока правильная

    // Проходим по каждому символу строки
    for (char ch : s) {
        // Если символ — открывающая скобка любого вида, кладём её в стек
        if (ch == '(' || ch == '[' || ch == '{') {
            st.push(ch);
        }
        // Если символ — закрывающая скобка
        else if (ch == ')' || ch == ']' || ch == '}') {
            // Закрывающая скобка без пары — ошибка
            if (st.empty()) { ok = false; break; }

            char top = st.top();  // смотрим вершину стека
            // Проверяем, что закрывающая скобка соответствует открывающей на вершине
            if ((ch == ')' && top == '(') ||
                (ch == ']' && top == '[') ||
                (ch == '}' && top == '{')) {
                st.pop();  // пара найдена — убираем открывающую из стека
            } else {
                ok = false;  // несовпадение видов скобок — ошибка
                break;
            }
        }
        // Все остальные символы (буквы, знаки препинания, пробелы) игнорируем
    }

    // Если после прохода стек не пуст — остались незакрытые открывающие скобки
    if (!st.empty()) ok = false;

    // Выводим результат: "yes" если правильная, иначе "no"
    cout << (ok ? "yes" : "no") << endl;
    return 0;
}